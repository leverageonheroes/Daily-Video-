def main():
    for ch, data in (("elders", ELDERS), ("cribcommittee", CRIB)):
        p = ROOT / "channels" / ch / "extras.json"
        p.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
        n = sum(len(f["episodes"]) for f in data["formats"].values())
        print(f"wrote {p.relative_to(ROOT)} ({n} episodes)")


