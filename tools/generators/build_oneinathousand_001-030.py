def build():
    eps = []
    for i, (slug, title, hook, note, tags, music, guests, locs, shots) in enumerate(EPISODES):
        n = i + 1
        pre = f"oit{n:03d}_"
        gmap = {g: pre + g for g in guests}
        ep_guests = {pre + g: {"name": g.capitalize(), "ref_prompt": ref, "voice": "none (narrated)"}
                     for g, ref in guests.items()}
        ep_locs = {pre + k: v for k, v in locs.items()}
        out_shots = []
        for k, ((loc, chars, visual, narr, sfx), dur) in enumerate(zip(shots, DURS)):
            out_shots.append({
                "n": k + 1, "dur": dur, "loc": pre + loc, "chars": [gmap[c] for c in chars],
                "keyframe": visual, "action": visual, "camera": CAMERAS[k],
                "lines": [], "narration": narr, "sfx": sfx})
        eps.append({
            "id": f"OIT-{n:03d}", "number": n, "theme": slug,
            "title": f"{title} #shorts", "logline": f"{slug}: {note[:160]}",
            "hook_text": hook,
            "description": (f"{note}\n\nOne In A Thousand: true survival stories, one every day. "
                            "Which creature should we follow next? Tell us below."),
            "tags": tags + ["one in a thousand", "animals", "nature documentary", "true story"],
            "music": music, "fact_note": note,
            "guests": ep_guests, "locations": ep_locs,
            "shots": out_shots,
            "loop_note": "the final line links back to the opening image (the next generation / the journey again)",
        })
    return eps


